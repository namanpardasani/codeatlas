"""Build the Replay page data: re-run Blast Radius on a few real bug-inducing commits from the dataset (only history
before them), and record where the bug was later fixed. Notes are written by hand; every number is computed here.

    uv run python -m analyzer.blast.evaluation.replays    # -> apps/web/src/data/replays.json
"""
import json
from pathlib import Path

from ..engine import analyze_commit
from ..impact import Params
from ..snapshot import InProcessParser
from ...parsing import supported

ROOT = Path(__file__).resolve().parents[5]
EVAL = ROOT / "eval" / "blast"
OUT = ROOT / "apps" / "web" / "src" / "data" / "replays.json"

PICKS = [
    ("flask:c6316132->1b40b3b5", "hit",
     "The change moved request-context preservation from the test client into Flask itself (ctx.py, globals.py). "
     "Blast Radius put flask/app.py first among files outside the diff, because app.py calls into the changed context "
     "code. The later fix for the teardown interaction landed exactly there."),
    ("requests:4bf88661->7c80222a", "hit",
     "select_proxy() learned an 'all' proxy key. adapters.py calls select_proxy and ranks first outside the diff. "
     "sessions.py, where the follow-up fix landed, ranks third, but only through a weak path (it imports adapters.py; "
     "score 0.07): a hit by rank, not a confident one."),
    ("axios:bb5f9a5a->4918457a", "miss",
     "The new fetch code wrapped network errors in AxiosError with a 'cause'. The bug was in AxiosError itself: the "
     "cause was enumerable and broke JSON.stringify. Blast Radius follows what DEPENDS ON the change (callers, "
     "importers, co-changed files), not what the change depends on, so AxiosError.js never appears. A known blind spot."),
]


def main() -> None:
    pairs = {}
    for name in ("pairs.json", "pairs_test.json", "pairs_test2.json"):
        for p in json.loads((EVAL / "dataset" / name).read_text())["pairs"]:
            pairs[p["id"]] = p
    repos = {r["name"]: r for r in json.loads((EVAL / "repos.json").read_text())["repos"]}
    out = []
    for pid, outcome, note in PICKS:
        p = pairs[pid]
        repo = EVAL / ".repos" / repos[p["repo"]]["dir"]
        rep = analyze_commit(repo, p["inducing"], parser=InProcessParser(), params=Params(tiered=True))
        changed = [f.path for f in rep.changes.files if f.status != "deleted"]
        fixed = sorted(f for f, s in p["fix_files"].items() if s == "M" and supported(f) and not f.startswith(("test", "tests/")))
        ranked = [f for f in rep.impact.files if supported(f.path_str)]
        beyond = [f for f in ranked if f.distance > 0]
        out.append({
            "id": pid, "repo": p["repo"], "outcome": outcome, "note": note,
            "inducing": {"sha": p["inducing"][:10], "subject": p["inducing_subject"], "time": p["inducing_time"]},
            "fix": {"sha": p["fix"][:10], "subject": p["fix_subject"], "time": p["fix_time"], "files": fixed},
            "changed": [{"path": f.path, "category": f.category, "symbols": [f"{s.change} {s.name}" for s in f.semantic_symbols][:6]}
                        for f in rep.changes.files][:12],
            "predicted": [{"path": f.path_str, "score": round(f.score, 3), "distance": f.distance,
                           "why": [s.reason for s in f.path][-4:]} for f in beyond[:10]],
            "fix_ranks": {g: next((i for i, f in enumerate(beyond, 1) if f.path_str == g), None) for g in fixed if g not in changed},
            "risk": {"score": rep.risk.score, "label": rep.risk.label, "top": rep.risk.top_factors} if rep.risk else None,
            "tests": rep.tests.summary() if rep.tests else None,
        })
        print(pid, out[-1]["fix_ranks"])
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({"note": "generated by analyzer.blast.evaluation.replays from the evaluation dataset", "replays": out}, indent=1))


if __name__ == "__main__":
    main()
