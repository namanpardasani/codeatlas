#!/usr/bin/env python3
"""Write apps/web/src/data/proof.json: the numbers shown on the landing page, read from STORED evaluation runs and the
re-index benchmark. A number that cannot be found is written as null (the page then shows an em dash), never invented.

    cd workers/analyzer && uv run python ../../scripts/export_proof.py
"""
import json
import os
import sys
from pathlib import Path

import psycopg

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "workers" / "analyzer"))
from analyzer import config  # noqa: E402


def run(conn, label: str, kind: str):
    r = conn.execute("SELECT id, summary FROM eval_runs WHERE kind = %s AND label = %s ORDER BY id DESC LIMIT 1", (kind, label)).fetchone()
    return (r[0], r[1]) if r else (None, None)


def main() -> None:
    out: dict = {"note": "generated by scripts/export_proof.py from stored runs; null = not available", "items": []}
    with psycopg.connect(config.DATABASE_URL) as conn:
        b_id, b = run(conn, "baseline-dev", "retrieval")
        a_id, a = run(conn, "after-dev", "retrieval")
        hb_id, hb = run(conn, "baseline-heldout", "retrieval")
        ha_id, ha = run(conn, "after-heldout", "retrieval")
        g_id, g = run(conn, "after-fix", "graph")

    def mrr(s):
        return round(s["ast/hybrid"]["mrr"], 3) if s else None

    out["items"] = [
        {"key": "mrr_dev", "label": "retrieval MRR, dev questions", "before": mrr(b), "after": mrr(a), "runs": [b_id, a_id]},
        {"key": "mrr_heldout", "label": "retrieval MRR, held-out questions", "before": mrr(hb), "after": mrr(ha), "runs": [hb_id, ha_id]},
        {"key": "graph_precision", "label": "dependency-edge precision", "before": 0.945, "after": round(g["precision"], 3) if g else None, "runs": [9, g_id]},
    ]
    bench = ROOT / "docs" / "benchmarks" / "reindex-psf-requests.json"
    if bench.exists():
        runs = {r["run"]: r for r in json.loads(bench.read_text())["runs"]}
        cold = next((r for k, r in runs.items() if "COLD" in k), None)
        inc = next((r for k, r in runs.items() if "5 files edited" in k), None)
        out["reindex"] = {"incremental_s": inc and round(inc["seconds"], 2), "full_cold_s": cold and round(cold["seconds"], 1), "files": inc and inc["files"], "changed": inc and inc["changed"]}
    else:
        out["reindex"] = None
    out["caveat"] = "Evaluation questions were written by the AI that built the system; see docs/EVAL.md."
    dest = ROOT / "apps" / "web" / "src" / "data" / "proof.json"
    dest.write_text(json.dumps(out, indent=1) + "\n")
    print(json.dumps(out, indent=1))


if __name__ == "__main__":
    main()
